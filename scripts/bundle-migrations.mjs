#!/usr/bin/env node
/**
 * Concatenate supabase/migrations/*.sql into apply-all-migrations.sql (fresh-project bootstrap).
 * Run: npm run db:bundle
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = path.join(root, "supabase", "migrations");
const outFile = path.join(root, "supabase", "apply-all-migrations.sql");

const files = (await readdir(migrationsDir))
  .filter((f) => f.endsWith(".sql"))
  .sort();

if (!files.length) {
  console.error("No migration files found in", migrationsDir);
  process.exit(1);
}

const header = `-- Smohix: all migrations in one file (run once in Supabase → SQL Editor → Run).
-- Fresh project only. Re-running may error on existing policies/objects.
-- Auto-generated by scripts/bundle-migrations.mjs — do not edit by hand.
-- Migration count: ${files.length}
-- Order:
${files.map((f, i) => `--   ${i + 1}. ${f}`).join("\n")}

`;

const parts = [header];
for (const file of files) {
  const sql = await readFile(path.join(migrationsDir, file), "utf8");
  parts.push(`-- =============================================================================\n-- ${file}\n-- =============================================================================\n\n`);
  parts.push(sql.trim());
  parts.push("\n\n");
}

await writeFile(outFile, parts.join(""), "utf8");
console.log(`Wrote ${outFile} (${files.length} migrations)`);
